export function findCompany(query: string): CompanyInfo | null {
  const normalizedQuery = query.toLowerCase().trim();
  
  // Exact match
  const exactMatch = knownCompanies.find(
    (c) => c.name.toLowerCase() === normalizedQuery
  );
  if (exactMatch) return exactMatch;

  // Partial match
  const partialMatch = knownCompanies.find(
    (c) =>
      c.name.toLowerCase().includes(normalizedQuery) ||
      normalizedQuery.includes(c.name.toLowerCase())
  );
  if (partialMatch) return partialMatch;

  // Fuzzy match - check if any company name words match
  const words = normalizedQuery.split(/\s+/);
  const fuzzyMatch = knownCompanies.find((c) =>
    words.some(
      (word) =>
        word.length > 3 &&
        c.name.toLowerCase().includes(word)
    )
  );
  if (fuzzyMatch) return fuzzyMatch;

  return null;
}

